#!/usr/bin/env bash
set -euo pipefail

: "${ARCHIVE:?Set ARCHIVE to the uploaded release ZIP}"
: "${ARCHIVE_SHA256:?Set ARCHIVE_SHA256 to the expected SHA-256}"
: "${PRODUCT_VERSION:?Set PRODUCT_VERSION}"
: "${SNAPPYMAIL_VERSION:?Set SNAPPYMAIL_VERSION}"
: "${SOURCE_COMMIT:?Set SOURCE_COMMIT}"
: "${RELEASE_BASE:?Set RELEASE_BASE}"
: "${DATA_PATH:?Set DATA_PATH}"
: "${CURRENT_LINK:?Set CURRENT_LINK}"
: "${HEALTH_URL:?Set HEALTH_URL}"

DATA_PATH="${DATA_PATH%/}"
RELEASE_BASE="${RELEASE_BASE%/}"

if [[ ! "$PRODUCT_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-.][0-9A-Za-z.-]+)?$ ]]; then
  echo "Invalid product version: $PRODUCT_VERSION" >&2
  exit 1
fi

if [[ ! "$SNAPPYMAIL_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Invalid SnappyMail version: $SNAPPYMAIL_VERSION" >&2
  exit 1
fi

if [[ ! "$SOURCE_COMMIT" =~ ^[0-9a-f]{40}$ ]]; then
  echo "SOURCE_COMMIT must be a full 40-character Git SHA" >&2
  exit 1
fi

for command in unzip sha256sum php curl python3; do
  command -v "$command" >/dev/null || {
    echo "Required command is missing on production: $command" >&2
    exit 1
  }
done

if [[ ! -f "$ARCHIVE" ]]; then
  echo "Release archive does not exist: $ARCHIVE" >&2
  exit 1
fi

actual_sha256="$(sha256sum "$ARCHIVE" | awk '{print $1}')"
if [[ "$actual_sha256" != "$ARCHIVE_SHA256" ]]; then
  echo "Release archive checksum mismatch" >&2
  exit 1
fi

if [[ ! -d "$DATA_PATH" || ! -f "$DATA_PATH/INSTALLED" ]]; then
  echo "Persistent production data is missing: $DATA_PATH" >&2
  exit 1
fi

installed_version="$(tr -d '\r\n' < "$DATA_PATH/INSTALLED")"
if [[ "$installed_version" != "$SNAPPYMAIL_VERSION" ]]; then
  echo "Production data expects SnappyMail $installed_version, release contains $SNAPPYMAIL_VERSION" >&2
  exit 1
fi

if [[ ! -L "$CURRENT_LINK" ]]; then
  echo "CURRENT_LINK must already be a symlink created by the one-time migration: $CURRENT_LINK" >&2
  exit 1
fi

if [[ "$DATA_PATH" == *"'"* ]]; then
  echo "DATA_PATH containing a single quote is not supported" >&2
  exit 1
fi

release_id="petuja-email-$PRODUCT_VERSION-${SOURCE_COMMIT:0:12}"
release_dir="$RELEASE_BASE/releases/$release_id"
staging_dir="$RELEASE_BASE/releases/.staging-$release_id-$$"

if [[ -e "$release_dir" ]]; then
  echo "Release directory already exists: $release_dir" >&2
  exit 1
fi

mkdir -p "$RELEASE_BASE/releases"
mkdir "$staging_dir"

cleanup_staging() {
  rm -rf "$staging_dir"
}
trap cleanup_staging EXIT

unzip -q "$ARCHIVE" -d "$staging_dir"

for required in \
  "index.php" \
  "LICENSE" \
  "snappymail/v/$SNAPPYMAIL_VERSION/include.php" \
  "snappymail/v/$SNAPPYMAIL_VERSION/app/petuja-product.json" \
  "snappymail/v/$SNAPPYMAIL_VERSION/static/images/petuja-systems-logo.svg"
do
  if [[ ! -e "$staging_dir/$required" ]]; then
    echo "Release archive is missing required path: $required" >&2
    exit 1
  fi
done

if ! grep -Fq "define('APP_VERSION', '$SNAPPYMAIL_VERSION')" "$staging_dir/index.php"; then
  echo "Release index.php does not point to SnappyMail $SNAPPYMAIL_VERSION" >&2
  exit 1
fi

python3 - "$staging_dir/snappymail/v/$SNAPPYMAIL_VERSION/app/petuja-product.json" \
  "$PRODUCT_VERSION" "$SNAPPYMAIL_VERSION" <<'PY'
import json
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
product_version = sys.argv[2]
snappymail_version = sys.argv[3]
data = json.loads(path.read_text(encoding="utf-8"))

expected = {
    "product": "petuja.email",
    "version": product_version,
    "snappymailVersion": snappymail_version,
}
for key, value in expected.items():
    if data.get(key) != value:
        raise SystemExit(
            f"Unexpected release metadata {key}: {data.get(key)!r} != {value!r}"
        )
PY

cat > "$staging_dir/include.php" <<PHP
<?php
// Production-only configuration generated by the petuja.email deployment pipeline.
define('APP_DATA_FOLDER_PATH', '${DATA_PATH}/');
PHP
chmod 600 "$staging_dir/include.php"

cat > "$staging_dir/.petuja-release.json" <<JSON
{
  "product": "petuja.email",
  "version": "$PRODUCT_VERSION",
  "snappymailVersion": "$SNAPPYMAIL_VERSION",
  "sourceCommit": "$SOURCE_COMMIT"
}
JSON
chmod 600 "$staging_dir/.petuja-release.json"

php -l "$staging_dir/index.php" >/dev/null
php -l "$staging_dir/include.php" >/dev/null

mv "$staging_dir" "$release_dir"
trap - EXIT

previous_release="$(readlink -f "$CURRENT_LINK")"
next_link="${CURRENT_LINK}.next.$$"
rollback_link="${CURRENT_LINK}.rollback.$$"

ln -s "$release_dir" "$next_link"
mv -Tf "$next_link" "$CURRENT_LINK"

health_query="petuja-deploy-check=${SOURCE_COMMIT:0:12}"
root_url="${HEALTH_URL%/}/?${health_query}"
asset_url="${HEALTH_URL%/}/snappymail/v/$SNAPPYMAIL_VERSION/static/images/petuja-systems-logo.svg?${health_query}"

if curl -fsS --connect-timeout 5 --max-time 20 --retry 2 -o /dev/null "$root_url" \
  && curl -fsS --connect-timeout 5 --max-time 20 --retry 2 -o /dev/null "$asset_url"; then
  echo "Deployment health check passed."
  echo "Current release: $CURRENT_LINK -> $(readlink -f "$CURRENT_LINK")"
  exit 0
fi

echo "Deployment health check failed; rolling back to $previous_release" >&2
ln -s "$previous_release" "$rollback_link"
mv -Tf "$rollback_link" "$CURRENT_LINK"

if curl -fsS --connect-timeout 5 --max-time 20 --retry 1 -o /dev/null "${HEALTH_URL%/}/"; then
  echo "Rollback health check passed." >&2
else
  echo "WARNING: rollback target is active but its HTTP health check also failed." >&2
fi

exit 1
